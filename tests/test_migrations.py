import unittest

from scripts.migrate_postgres import migration_files


class MigrationDefinitionTest(unittest.TestCase):
    def test_versions_are_contiguous_and_schema_is_non_destructive(self):
        files = migration_files()
        self.assertEqual([version for version, _ in files], [1])
        sql = "\n".join(path.read_text(encoding="utf-8") for _, path in files).upper()
        for destructive in ("DROP TABLE", "TRUNCATE", "DELETE FROM"):
            self.assertNotIn(destructive, sql)

    def test_financial_and_concurrency_constraints_exist(self):
        sql = migration_files()[0][1].read_text(encoding="utf-8").upper()
        self.assertIn("NUMERIC(18,2)", sql)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", sql)
        self.assertIn("UQ_DOCUMENTS_SOURCE_TYPE", sql)
        self.assertIn("UNIQUE", sql)


if __name__ == "__main__":
    unittest.main()
