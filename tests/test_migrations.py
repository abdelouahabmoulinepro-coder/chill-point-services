import unittest
from pathlib import Path

from core.database import POSTGRES_SCHEMA_VERSION
from scripts.migrate_postgres import migration_files


class MigrationDefinitionTest(unittest.TestCase):
    def test_versions_are_contiguous_and_schema_is_non_destructive(self):
        files = migration_files()
        self.assertEqual([version for version, _ in files], [1, 2])
        sql = "\n".join(path.read_text(encoding="utf-8") for _, path in files).upper()
        for destructive in ("DROP TABLE", "TRUNCATE", "DELETE FROM"):
            self.assertNotIn(destructive, sql)

    def test_financial_and_concurrency_constraints_exist(self):
        sql = migration_files()[0][1].read_text(encoding="utf-8").upper()
        self.assertIn("NUMERIC(18,2)", sql)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", sql)
        self.assertIn("UQ_DOCUMENTS_SOURCE_TYPE", sql)
        self.assertIn("UNIQUE", sql)

    def test_auth_session_migration_contains_no_credentials_or_business_changes(self):
        sql = migration_files()[1][1].read_text(encoding="utf-8").upper()
        self.assertIn("SESSION_ID_HASH", sql)
        self.assertIn("REVOKED_AT", sql)
        for forbidden_column in ("PASSWORD TEXT", "PASSWORD_HASH", "SECRET TEXT", "TOKEN TEXT"):
            self.assertNotIn(forbidden_column, sql)
        self.assertNotIn("DOCUMENTS", sql)

    def test_readiness_check_tracks_current_schema_and_auth_privileges(self):
        self.assertEqual(POSTGRES_SCHEMA_VERSION, 2)
        source = (Path(__file__).parent.parent / "scripts" / "production_readiness.py").read_text(
            encoding="utf-8"
        )
        self.assertIn("version != POSTGRES_SCHEMA_VERSION", source)
        self.assertIn('"auth_sessions"', source)
        self.assertIn('(\"INSERT\", \"UPDATE\")', source)
        self.assertIn("args.require_empty_business_data", source)

        backup_source = (
            Path(__file__).parent.parent / "scripts" / "backup_postgres.py"
        ).read_text(encoding="utf-8")
        self.assertIn("str(POSTGRES_SCHEMA_VERSION)", backup_source)


if __name__ == "__main__":
    unittest.main()
