CREATE TABLE company_settings (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    name TEXT NOT NULL,
    slogan TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    tax_id TEXT NOT NULL DEFAULT '',
    registration TEXT NOT NULL DEFAULT '',
    fiscal_id TEXT NOT NULL DEFAULT '',
    rc TEXT NOT NULL DEFAULT '',
    patente TEXT NOT NULL DEFAULT '',
    cnss TEXT NOT NULL DEFAULT '',
    rib TEXT NOT NULL DEFAULT '',
    swift TEXT NOT NULL DEFAULT '',
    logo_path TEXT NOT NULL DEFAULT 'assets/logo-moderne-final.png',
    show_prices_on_delivery_note BOOLEAN NOT NULL DEFAULT TRUE,
    currency TEXT NOT NULL DEFAULT 'MAD',
    default_vat NUMERIC(7,4) NOT NULL DEFAULT 20 CHECK (default_vat BETWEEN 0 AND 100),
    bank_details TEXT NOT NULL DEFAULT '',
    document_footer TEXT NOT NULL DEFAULT ''
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE,
    name TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'Entreprise',
    contact_name TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    tax_id TEXT NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT UNIQUE,
    name TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'Service',
    description TEXT NOT NULL DEFAULT '',
    unit TEXT NOT NULL DEFAULT 'unité',
    unit_price NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
    vat_rate NUMERIC(7,4) NOT NULL DEFAULT 0 CHECK (vat_rate BETWEEN 0 AND 100),
    stock_quantity NUMERIC(18,4) NOT NULL DEFAULT 0,
    track_stock BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sequences (
    doc_type TEXT NOT NULL,
    year INTEGER NOT NULL,
    last_value BIGINT NOT NULL DEFAULT 0 CHECK (last_value >= 0),
    PRIMARY KEY (doc_type, year)
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_type TEXT NOT NULL,
    number TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    issue_date DATE NOT NULL,
    due_date DATE,
    status TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    terms TEXT NOT NULL DEFAULT '',
    subtotal NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    tax_total NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
    total NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    paid_amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0 AND paid_amount <= total),
    currency TEXT NOT NULL,
    source_document_id BIGINT REFERENCES documents(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_documents_source_type
    ON documents(source_document_id, doc_type)
    WHERE source_document_id IS NOT NULL;

CREATE TABLE document_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    item_id BIGINT REFERENCES items(id),
    description TEXT NOT NULL,
    quantity NUMERIC(18,4) NOT NULL CHECK (quantity > 0),
    unit TEXT NOT NULL DEFAULT 'unité',
    unit_price NUMERIC(18,4) NOT NULL CHECK (unit_price >= 0),
    discount_rate NUMERIC(7,4) NOT NULL DEFAULT 0 CHECK (discount_rate BETWEEN 0 AND 100),
    vat_rate NUMERIC(7,4) NOT NULL DEFAULT 0 CHECK (vat_rate BETWEEN 0 AND 100),
    line_subtotal NUMERIC(18,2) NOT NULL CHECK (line_subtotal >= 0),
    line_tax NUMERIC(18,2) NOT NULL CHECK (line_tax >= 0),
    line_total NUMERIC(18,2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    payment_date DATE NOT NULL,
    amount NUMERIC(18,2) NOT NULL CHECK (amount > 0),
    method TEXT NOT NULL,
    reference TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE client_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    company_name TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    request_type TEXT NOT NULL,
    subject TEXT NOT NULL DEFAULT '',
    message TEXT NOT NULL,
    preferred_contact TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'Nouvelle',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_documents_type_date ON documents(doc_type, issue_date);
CREATE INDEX idx_documents_customer ON documents(customer_id);
CREATE INDEX idx_payments_document ON payments(document_id);
CREATE INDEX idx_client_requests_status_date ON client_requests(status, created_at);

